//! Writes notary/vectors/attestation/genesis_attestations.json: purpose-0x01 simulator attestations bound to the
//! genesis request in vectors/objects/genesis_request.json, good and bad, for algorithm G tests (step 5.4).
use notary_attest::aws::build::{build_document, pcrs, DocFields};
use notary_sim::test_pki;
use notary_types::{b64u, formats, jcs, user_data::UserData};
use serde_json::{json, Value};
use sha2::{Digest, Sha256};

fn vec_path(rel: &str) -> std::path::PathBuf {
    std::path::PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../vectors").join(rel)
}

#[test]
fn write_genesis_attestations() {
    if std::env::var("NOTARY_WRITE_VECTORS").is_err() {
        return;
    }
    let f: Value = serde_json::from_str(&std::fs::read_to_string(vec_path("objects/genesis_request.json")).unwrap()).unwrap();
    let mut req = f["cases"][0]["input"].clone();
    req["platform"] = json!("simulator"); // the request names the platform of the enclave that attests it
    let req = &req;
    let nonce = jcs::h_bytes(req).unwrap();
    let id_pub = b64u::decode(req["id_pubkey"].as_str().unwrap()).unwrap();
    let id_hash: [u8; 32] = { let h = formats::card_pointer(&id_pub); (0..32).map(|i| u8::from_str_radix(&h[2 * i..2 * i + 2], 16).unwrap()).collect::<Vec<_>>().try_into().unwrap() };
    let chain_hash: [u8; 32] = Sha256::digest(b64u::decode(req["chain_pubkey"].as_str().unwrap()).unwrap()).into();
    let pki = test_pki();
    let ts = formats::parse_timestamp("2026-11-12T10:00:00Z").unwrap() as u64;
    let ud = |idk: [u8; 32], ck: [u8; 32]| UserData { purpose: 0x01, id_key_hash: idk, chain_key_hash: ck, inst_key_hash: [0x5A; 32], ..Default::default() };
    let build = |seed: u8, debug: bool, u: UserData, n: [u8; 32], pk: Option<Vec<u8>>| {
        let mut d = DocFields::new(&pki, ts, pcrs(seed, debug));
        d.user_data = Some(u.encode().to_vec());
        d.nonce = Some(n.to_vec());
        d.public_key = pk;
        b64u::encode(&build_document(&d, &pki.leaf_key))
    };
    let mut other_nonce = nonce;
    other_nonce[0] ^= 1;
    let docs = json!({
        "good": build(0x10, false, ud(id_hash, chain_hash), nonce, None),
        "wrong_nonce": build(0x10, false, ud(id_hash, chain_hash), other_nonce, None),
        "wrong_chain_key": build(0x10, false, ud(id_hash, [9; 32]), nonce, None),
        "wrong_id_key": build(0x10, false, ud([9; 32], chain_hash), nonce, None),
        "has_public_key": build(0x10, false, ud(id_hash, chain_hash), nonce, Some(vec![1; 32])),
        "debug": build(0x10, true, ud(id_hash, chain_hash), nonce, None),
        "other_pcr0": build(0x99, false, ud(id_hash, chain_hash), nonce, None),
    });
    let out = json!({ "note": "Generated by notary/sim/tests/genesis_fixtures.rs", "now_ms": ts, "trust_root": b64u::encode(&pki.root_der), "accepted_pcr0": b64u::encode(&[0x10u8; 48]), "docs": docs });
    std::fs::write(vec_path("attestation/genesis_attestations.json"), serde_json::to_string_pretty(&out).unwrap() + "\n").unwrap();
}
