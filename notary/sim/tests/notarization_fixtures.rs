//! Writes notary/vectors/attestation/notarization_attestations.json: purpose-0x02 attestations for a closing
//! replica and cosigning replicas (simulator), good and bad, for the algorithm N tests (step 5.4).
//! Inputs come from vectors/attestation/notarization_spec.json (written by vectors-tools).
use notary_attest::aws::build::{build_document, pcrs, DocFields};
use notary_sim::test_pki;
use notary_types::{b64u, formats, user_data::UserData};
use serde_json::{json, Value};
use sha2::{Digest, Sha256};

fn vec_path(rel: &str) -> std::path::PathBuf {
    std::path::PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../vectors").join(rel)
}

#[test]
fn write_notarization_attestations() {
    if std::env::var("NOTARY_WRITE_VECTORS").is_err() {
        return;
    }
    let spec: Value = serde_json::from_str(&std::fs::read_to_string(vec_path("attestation/notarization_spec.json")).unwrap()).unwrap();
    let h32 = |s: &str| -> [u8; 32] { b64u::decode_len(s, 32).unwrap().try_into().unwrap() };
    let job_hash = h32(spec["job_hash"].as_str().unwrap());
    let program = formats::digest_from_cid(spec["program_cid"].as_str().unwrap()).unwrap();
    let card = spec["notary_card"].as_str().unwrap();
    let id: [u8; 32] = (0..32).map(|i| u8::from_str_radix(&card[2 * i..2 * i + 2], 16).unwrap()).collect::<Vec<_>>().try_into().unwrap();
    let ts = formats::parse_timestamp(spec["timestamp"].as_str().unwrap()).unwrap() as u64;
    let insts: Vec<[u8; 32]> = spec["instance_public_keys"].as_array().unwrap().iter()
        .map(|k| Sha256::digest(b64u::decode(k.as_str().unwrap()).unwrap()).into()).collect();
    let pki = test_pki();
    let make = |seed: u8, debug: bool, ud: UserData, nonce: [u8; 32]| {
        let mut f = DocFields::new(&pki, ts, pcrs(seed, debug));
        f.user_data = Some(ud.encode().to_vec());
        f.nonce = Some(nonce.to_vec());
        f.public_key = Some(vec![0x44; 32]); // N does not compare the job key (E13) but requires it present
        b64u::encode(&build_document(&f, &pki.leaf_key))
    };
    let ud = |idk: [u8; 32], inst: [u8; 32], prog: [u8; 32], epoch: u64| UserData {
        purpose: 0x02, id_key_hash: idk, inst_key_hash: inst, program_hash: prog, job_hash, epoch, isolation: 0x01, ..Default::default()
    };
    let mut other_prog = program;
    other_prog[0] ^= 1;
    let mut bad_nonce = job_hash;
    bad_nonce[0] ^= 1;
    let docs = json!({
        "closer": make(0x10, false, ud(id, insts[0], program, 0), job_hash),
        "cosig_1": make(0x10, false, ud(id, insts[1], program, 0), job_hash),
        "cosig_2": make(0x10, false, ud(id, insts[2], program, 0), job_hash),
        "closer_wrong_program": make(0x10, false, ud(id, insts[0], other_prog, 0), job_hash),
        "closer_debug": make(0x10, true, ud(id, insts[0], program, 0), job_hash),
        "closer_wrong_nonce": make(0x10, false, ud(id, insts[0], program, 0), bad_nonce),
        "closer_wrong_epoch": make(0x10, false, ud(id, insts[0], program, 1), job_hash),
        "closer_other_pcr0": make(0x99, false, ud(id, insts[0], program, 0), job_hash),
        "cosig_1_wrong_instance": make(0x10, false, ud(id, insts[2], program, 0), job_hash), // binds instance 2's key, presented by instance 1
        "cosig_1_stranger_id": make(0x10, false, ud([0x77; 32], insts[1], program, 0), job_hash),
    });
    let out = json!({
        "note": "Generated by notary/sim/tests/notarization_fixtures.rs", "trust_root": b64u::encode(&pki.root_der),
        "accepted_pcr0": b64u::encode(&[0x10u8; 48]), "docs": docs,
    });
    std::fs::write(vec_path("attestation/notarization_attestations.json"), serde_json::to_string_pretty(&out).unwrap() + "\n").unwrap();
}
