//! Writes notary/vectors/attestation/job_attestations.json: per-job attestations (purpose 0x02) in the
//! simulator, good and bad, bound to the job in vectors/objects/announcement.json. The wallet SDK's
//! algorithm W tests (step 5.4) use them with real documents, not mocks. NOTARY_WRITE_VECTORS=1 writes.
use notary_attest::aws::build::{build_document, pcrs, DocFields};
use notary_sim::test_pki;
use notary_types::{b64u, formats, jcs, user_data::UserData};
use serde_json::{json, Value};
use sha2::{Digest, Sha256};

fn vec_path(rel: &str) -> std::path::PathBuf {
    std::path::PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../vectors").join(rel)
}

#[test]
fn write_job_attestations() {
    if std::env::var("NOTARY_WRITE_VECTORS").is_err() {
        return;
    }
    let ann: Value = serde_json::from_str(&std::fs::read_to_string(vec_path("objects/announcement.json")).unwrap()).unwrap();
    let ann = &ann["cases"][0]["input"];
    let notarization: Value = serde_json::from_str(&std::fs::read_to_string(vec_path("objects/notarization.json")).unwrap()).unwrap();
    let program_cid = notarization["cases"][0]["input"]["program_cid"].as_str().unwrap().to_string();
    let program_hash = formats::digest_from_cid(&program_cid).unwrap();
    let job_hash = jcs::h_bytes(&ann["job"]).unwrap();
    let k_id = b64u::decode(ann["notary_signature"]["public_key"].as_str().unwrap()).unwrap();
    let id_hash: [u8; 32] = sha3_keccak(&k_id);
    let job_pk = b64u::decode(ann["job_public_key"].as_str().unwrap()).unwrap();
    let pk_hash: [u8; 32] = Sha256::digest(&job_pk).into();
    let pki = test_pki();
    let now = formats::parse_timestamp("2026-11-12T10:00:00Z").unwrap();
    let inst = [0x5Au8; 32];

    let ud = |program: [u8; 32], id: [u8; 32], epoch: u64| UserData {
        purpose: 0x02, id_key_hash: id, inst_key_hash: inst, program_hash: program, job_hash, epoch, isolation: 0x01, ..Default::default()
    };
    let make = |seed: u8, debug: bool, ts: i64, user: UserData, nonce: [u8; 32], public_key: [u8; 32]| {
        let mut f = DocFields::new(&pki, ts as u64, pcrs(seed, debug));
        f.user_data = Some(user.encode().to_vec());
        f.nonce = Some(nonce.to_vec());
        f.public_key = Some(public_key.to_vec());
        b64u::encode(&build_document(&f, &pki.leaf_key))
    };
    let mut other_program = program_hash;
    other_program[0] ^= 1;
    let stranger = [0x77u8; 32];
    let mut wrong_nonce = job_hash;
    wrong_nonce[5] ^= 1;
    let docs = json!({
        "good": make(0x10, false, now, ud(program_hash, id_hash, 0), job_hash, pk_hash),
        "wrong_pcr0": make(0x99, false, now, ud(program_hash, id_hash, 0), job_hash, pk_hash),
        "debug": make(0x10, true, now, ud(program_hash, id_hash, 0), job_hash, pk_hash),
        "wrong_program": make(0x10, false, now, ud(other_program, id_hash, 0), job_hash, pk_hash),
        "wrong_nonce": make(0x10, false, now, ud(program_hash, id_hash, 0), wrong_nonce, pk_hash),
        "stale": make(0x10, false, now - 3 * 86_400_000, ud(program_hash, id_hash, 0), job_hash, pk_hash),
        "wrong_epoch": make(0x10, false, now, ud(program_hash, id_hash, 1), job_hash, pk_hash),
        "stranger_id_key": make(0x10, false, now, ud(program_hash, stranger, 0), job_hash, pk_hash),
        "wrong_public_key": make(0x10, false, now, ud(program_hash, id_hash, 0), job_hash, [0x11; 32]),
    });
    let out = json!({
        "note": "Purpose-0x02 simulator attestations bound to the job in objects/announcement.json. Generated by notary/sim/tests/job_fixtures.rs.",
        "now_ms": now, "program_cid": program_cid, "trust_root": b64u::encode(&pki.root_der), "accepted_pcr0": b64u::encode(&[0x10u8; 48]),
        "docs": docs,
    });
    std::fs::write(vec_path("attestation/job_attestations.json"), serde_json::to_string_pretty(&out).unwrap() + "\n").unwrap();
}

fn sha3_keccak(b: &[u8]) -> [u8; 32] {
    let hex = formats::card_pointer(b);
    let mut o = [0u8; 32];
    for i in 0..32 {
        o[i] = u8::from_str_radix(&hex[2 * i..2 * i + 2], 16).unwrap();
    }
    o
}
