//! notary-cards — card checks inside the enclave (step 5.3a; code-plan §7.5).
//!
//! A port of exactly the verifier logic that input checks B5–B8 (notary_lifecycle.md Appendix B) need:
//! - `stage2`: the signing sub-card (twin of `verifier/src/stages/stage2.ts`);
//! - `stage3`: the chain walk to a trusted root (twin of `stage3.ts`), with roots pinned in the image (E29);
//! - `stage4`: revocation and `expires_at` from head content and the on-chain event replay (twin of `stage4.ts`),
//!   judged at **chain time** (the TypeScript verifier uses its wall clock; the vectors use dates far from both);
//! - `predicates`: the predicate system with parameter references (twin of `verifier/src/notary/predicates.ts`, E28);
//! - `contributor`: B5–B8 and the root key (twin of `verifier/src/notary/contributor.ts`).
//!
//! **Kept in step by vectors**, not by reading the TypeScript: `notary/vectors/cards/cases.json` is generated by the
//! TypeScript verifier, regenerated in CI, and `tests/conformance.rs` requires the same verdict and code for every case.
//! Card documents come from a `CardSource` (registry entries + IPFS objects): in the vectors a JSON world, in the enclave
//! the input's `evidence` and the host's whole-policy snapshots.
